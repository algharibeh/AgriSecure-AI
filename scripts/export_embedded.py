"""Quantise the exported tiny model to int8 and emit the embedded reference.

Part of the AgriSecure-AI project.

Reads results/tiny_model.npz (from train_tiny_model.py), takes the model it
marks as exported (the spread-consistency model, SPR), quantises every weight
matrix to int8 with one symmetric scale per tensor (biases, feature mean/scale
and the threshold stay float32), and writes:

  embedded/model_weights.h   int8 weights, scales, biases, input/target feature
                             indices, normalisation, threshold
  embedded/test_vectors.h    64 raw feature windows from the attacked fields with
                             the score the quantised Python model produces, for
                             checking that the C inference matches
  results/footprint_phase2.json   static byte counts against the 10 KB target, and
                             the quantised model's detection metrics vs the
                             float model on the same test windows

The C inference itself is embedded/tiny_ids.c (hand-written, dependency-free).
Compiling it needs a C compiler, which this PC does not have; the compile and
the Cortex-M size measurement are done elsewhere and recorded in
REPORT_phase2.md with the command used.

Run: .venv/Scripts/python.exe -I scripts/export_embedded.py
"""
from __future__ import annotations
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C
import detect_baseline as B

ROOT = Path(__file__).resolve().parent.parent
EMB = ROOT / "embedded"
N_TEST_VECTORS = 64
SEED = 20261015


def quantise(W: np.ndarray):
    s = float(np.abs(W).max() / 127.0) if np.abs(W).max() > 0 else 1.0
    q = np.clip(np.round(W / s), -127, 127).astype(np.int8)
    return q, np.float32(s)


def load_model(npz_path, name=None):
    m = np.load(npz_path, allow_pickle=False)
    name = name or str(m["exported"])
    n = sum(1 for k in m.files if k.startswith(f"{name}_W"))
    layers = []
    for i in range(n):
        Wq, s = quantise(m[f"{name}_W{i}"])
        layers.append((Wq, s, m[f"{name}_b{i}"].astype(np.float32)))
    return {"name": name, "layers": layers, "in": [int(i) for i in m[f"{name}_in"]],
            "out": int(m[f"{name}_out"]), "thr": np.float32(m[f"{name}_thr"]),
            "mu": m["mu"].astype(np.float32), "sd": m["sd"].astype(np.float32),
            "features": [str(f) for f in m["features"]]}


def forward_f32(Zin: np.ndarray, layers) -> np.ndarray:
    """Float32 forward pass with dequantised int8 weights; mirrors tiny_ids.c."""
    h = Zin.astype(np.float32)
    n = len(layers)
    for i, (Wq, s, b) in enumerate(layers):
        h = h @ (Wq.astype(np.float32) * s) + b.astype(np.float32)
        if i < n - 1:
            h = np.maximum(h, np.float32(0))
    return h


def score_f32(model, X: np.ndarray) -> np.ndarray:
    Z = ((X - model["mu"]) / model["sd"]).astype(np.float32)
    h = forward_f32(Z[:, model["in"]], model["layers"])
    if model["out"] >= 0:
        return (h[:, 0] - Z[:, model["out"]]) ** 2
    return ((h - Z) ** 2).mean(axis=1)


def c_array(name, arr, ctype):
    flat = np.asarray(arr).ravel()
    if ctype in ("int8_t", "int"):
        body = ", ".join(str(int(v)) for v in flat)
    else:
        body = ", ".join(c_float(v) for v in flat)
    return f"static const {ctype} {name}[{flat.size}] = {{{body}}};\n"


def c_float(v) -> str:
    """Float literal with an 'f' suffix; integer-valued floats get a '.0' so the
    literal is not parsed as an integer constant."""
    s = f"{float(v):.9g}"
    if not any(ch in s for ch in ".eEn"):
        s += ".0"
    return s + "f"


def write_header(model):
    layers = model["layers"]
    sizes = [len(model["in"])] + [W.shape[1] for W, _, _ in layers]
    n_feat = len(model["features"])
    h = ["/* AgriSecure-AI tiny model, int8 weights. Generated by",
         " * scripts/export_embedded.py; do not edit. Layout: W[i] is row-major",
         " * [n_in][n_out] as in scikit-learn coefs_. Dequantise as W * S.",
         f" * Model: {model['name'].upper()}; inputs = feature indices TM_IN_IDX;",
         " * target = feature TM_OUT_IDX (-1 would mean reconstruction of all). */",
         "#ifndef AGRISECURE_MODEL_WEIGHTS_H", "#define AGRISECURE_MODEL_WEIGHTS_H",
         "#include <stdint.h>", "",
         f"#define TM_N_FEAT {n_feat}", f"#define TM_N_LAYERS {len(layers)}",
         f"#define TM_N_IN {sizes[0]}", f"#define TM_MAX_WIDTH {max(sizes + [n_feat])}",
         f"#define TM_OUT_IDX {model['out']}",
         "static const int TM_SIZES[TM_N_LAYERS + 1] = {" + ", ".join(map(str, sizes)) + "};",
         c_array("TM_IN_IDX", model["in"], "int").rstrip(),
         f"static const float TM_THRESHOLD = {c_float(model['thr'])};",
         "/* features: " + ", ".join(f"{i}={f}" for i, f in enumerate(model["features"])) + " */", ""]
    h.append(c_array("TM_MU", model["mu"], "float"))
    h.append(c_array("TM_SD", model["sd"], "float"))
    for i, (Wq, s, b) in enumerate(layers):
        h.append(c_array(f"TM_W{i}", Wq, "int8_t"))
        h.append(f"static const float TM_S{i} = {c_float(s)};\n")
        h.append(c_array(f"TM_B{i}", b, "float"))
    n = len(layers)
    h.append("static const int8_t *const TM_W[TM_N_LAYERS] = {" + ", ".join(f"TM_W{i}" for i in range(n)) + "};")
    h.append("static const float TM_S[TM_N_LAYERS] = {" + ", ".join(f"TM_S{i}" for i in range(n)) + "};")
    h.append("static const float *const TM_B[TM_N_LAYERS] = {" + ", ".join(f"TM_B{i}" for i in range(n)) + "};")
    h.append("#endif\n")
    (EMB / "model_weights.h").write_text("\n".join(h))
    return sizes


def main():
    model = load_model(C.RESULTS_DIR / "tiny_model.npz")
    EMB.mkdir(exist_ok=True)
    sizes = write_header(model)

    # ---- quantised vs float metrics on the test windows -----------------
    X = np.load(C.RESULTS_DIR / "test_features_phase2.npy")
    T = pd.read_parquet(C.RESULTS_DIR / "test_windows_phase2.parquet")
    assert len(X) == len(T), "features and windows out of step; rerun train_tiny_model.py"
    s_q = score_f32(model, X)
    flag_q = s_q > model["thr"]
    y = T["y"].to_numpy().astype(bool)
    name = model["name"]
    flag_f = T[name].to_numpy()
    hyb_q = T["rule"].to_numpy() | flag_q
    per_family = {}
    for fam, idx in T[T["y"] == 1].groupby("ytype").indices.items():
        per_family[fam] = {"int8": round(float(flag_q[idx].mean()), 4),
                           "float": round(float(flag_f[idx].mean()), 4)}
    agree = float((flag_q == flag_f).mean())

    # ---- test vectors ----------------------------------------------------
    rng = np.random.default_rng(SEED)
    atk_idx = np.where(y)[0]
    clean_idx = np.where(~y)[0]
    pick = np.concatenate([rng.choice(atk_idx, N_TEST_VECTORS // 2, replace=False),
                           rng.choice(clean_idx, N_TEST_VECTORS - N_TEST_VECTORS // 2, replace=False)])
    pick.sort()
    tv = ["/* Test vectors: raw window features and the quantised model's score.",
          " * Generated by scripts/export_embedded.py. */",
          "#ifndef AGRISECURE_TEST_VECTORS_H", "#define AGRISECURE_TEST_VECTORS_H",
          f"#define TV_N {len(pick)}",
          c_array("TV_X", X[pick], "float"),
          c_array("TV_SCORE", s_q[pick], "float"),
          c_array("TV_FLAG", flag_q[pick].astype(np.int8), "int8_t"),
          "#endif\n"]
    (EMB / "test_vectors.h").write_text("\n".join(tv))

    # ---- footprint -------------------------------------------------------
    layers = model["layers"]
    n_w = sum(int(W.size) for W, _, _ in layers)
    n_b = sum(int(b.size) for _, _, b in layers)
    n_feat = len(model["features"])
    weights_b = n_w                            # int8
    bias_scale_b = 4 * (n_b + len(layers))     # float32 biases + per-tensor scales
    idx_b = 4 * len(model["in"])               # input index table (int)
    norm_b = 4 * (2 * n_feat) + 4              # mu, sd, threshold
    act_b = 4 * 2 * max(sizes + [n_feat])      # two float32 activation buffers
    window_b = 4 * 10 * 4 + 2                  # 1 s ring buffer, 4 signals at 100 ms, head/count
    feat_b = 4 * n_feat                        # feature vector
    rule_b = 8 * 32                            # Phase 1 rule state per PGN (sizeof(rule_state_t) = 32, measured)
    total = weights_b + bias_scale_b + idx_b + norm_b + act_b + window_b + feat_b + rule_b
    fp = {
        "target_bytes": 10 * 1024,
        "model": {"name": name, "layers": sizes, "n_weights": n_w, "n_biases": n_b,
                  "inputs": [model["features"][i] for i in model["in"]],
                  "target": model["features"][model["out"]] if model["out"] >= 0 else "reconstruction"},
        "bytes": {"weights_int8": weights_b, "biases_and_scales_f32": bias_scale_b,
                  "input_index_table": idx_b,
                  "normalisation_and_threshold_f32": norm_b, "activations_f32": act_b,
                  "window_ring_buffer_f32": window_b, "feature_vector_f32": feat_b,
                  "rule_state_8_pgns": rule_b, "total_static": total},
        "under_target": total < 10 * 1024,
        "quantisation": {"scheme": "int8 symmetric per-tensor weights; float32 biases, activations",
                         "flag_agreement_with_float": round(agree, 6),
                         "window_level_int8": B.metrics(y, flag_q),
                         "window_level_float": B.metrics(y, flag_f),
                         "hybrid_int8": B.metrics(y, hyb_q),
                         "per_family": per_family},
        "test_vectors": {"n": int(len(pick)), "file": "embedded/test_vectors.h"},
        "note": "Static counts from the exported tensors and the C struct layout; "
                "compiled flash/RAM sizes are recorded separately in REPORT_phase2.md.",
    }
    (C.RESULTS_DIR / "footprint_phase2.json").write_text(json.dumps(fp, indent=2))
    print(json.dumps(fp, indent=2))
    print(f"\nwrote {EMB / 'model_weights.h'}, {EMB / 'test_vectors.h'}")


if __name__ == "__main__":
    main()
